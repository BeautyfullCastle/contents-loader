using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;

namespace H.ContentsLoader.Editor
{
    // 오타 방지용 상수. ContentPaths.Towers.Cannon == "Towers/Cannon"
    internal static class PathConstantsGenerator
    {
        sealed class Folder
        {
            public readonly SortedDictionary<string, Folder> Children = new(System.StringComparer.Ordinal);
            public readonly SortedDictionary<string, string> Paths = new(System.StringComparer.Ordinal);
        }

        [MenuItem("Tools/Contents Loader/Generate Path Constants")]
        static void GenerateFromMenu()
        {
            var settings = ContentsSettings.FindOrDefault();
            Write(settings.PathConstantsFile, ContentsScanner.ScanProject().Entries.Select(e => e.Path));
            AssetDatabase.Refresh();
        }

        public static void Write(string file, IEnumerable<string> paths)
        {
            var source = Generate(paths);
            if (File.Exists(file) && File.ReadAllText(file) == source) return;
            Directory.CreateDirectory(Path.GetDirectoryName(file)!);
            File.WriteAllText(file, source);
        }

        public static string Generate(IEnumerable<string> paths)
        {
            var root = new Folder();
            foreach (var path in paths)
            {
                var parts = path.Split('/');
                var folder = root;
                for (var i = 0; i < parts.Length - 1; i++)
                {
                    var name = Identifier(parts[i]);
                    if (!folder.Children.TryGetValue(name, out var child)) folder.Children.Add(name, child = new Folder());
                    folder = child;
                }
                var constant = Identifier(parts[^1]);
                // 이름 정리 후 겹치면 컴파일 오류가 나므로 뒤에 _를 붙여 구분함
                while (folder.Paths.ContainsKey(constant)) constant += "_";
                folder.Paths[constant] = path;
            }

            var code = new StringBuilder();
            code.AppendLine("// <auto-generated>Contents Loader가 생성함. 직접 고치지 않음</auto-generated>");
            code.AppendLine("public static class ContentPaths");
            code.AppendLine("{");
            WriteFolder(code, root, 1, "ContentPaths");
            code.AppendLine("}");
            return code.ToString();
        }

        static void WriteFolder(StringBuilder code, Folder folder, int depth, string className)
        {
            var indent = new string(' ', depth * 4);
            foreach (var kv in folder.Paths)
            {
                var name = kv.Key == className || folder.Children.ContainsKey(kv.Key) ? kv.Key + "_" : kv.Key;
                code.AppendLine($"{indent}public const string {name} = \"{kv.Value}\";");
            }
            foreach (var kv in folder.Children)
            {
                var name = kv.Key == className ? kv.Key + "_" : kv.Key;
                code.AppendLine($"{indent}public static class {name}");
                code.AppendLine($"{indent}{{");
                WriteFolder(code, kv.Value, depth + 1, name);
                code.AppendLine($"{indent}}}");
            }
        }

        static string Identifier(string name)
        {
            var builder = new StringBuilder();
            foreach (var c in name) builder.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            if (builder.Length == 0 || char.IsDigit(builder[0])) builder.Insert(0, '_');
            return builder.ToString();
        }
    }
}
